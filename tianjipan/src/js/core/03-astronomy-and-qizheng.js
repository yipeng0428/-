function xlrQi(m, d, h) {
  const p1 = (m - 1 + d - 1) % 6,
    p2 = (p1 + h - 1) % 6;
  return {
    yue: XLR_SHEN[(m - 1) % 6],
    ri: XLR_SHEN[p1],
    shi: XLR_SHEN[p2],
    p: [(m - 1) % 6, p1, p2],
  };
}
