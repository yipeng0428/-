function p5Fan(Y, b) {
  // Y:流年岁支下标,b:生肖(出生年支)下标
  const r = [];
  if (Y === b) r.push({ k: "值", n: "值太岁(本命年)", tone: "xiong" });
  if ((Y + 6) % 12 === b) r.push({ k: "冲", n: "冲太岁", tone: "xiong" });
  const xing =
    (Y === b && P5_ZIXING.includes(Y)) ||
    (Y !== b &&
      ((Y === 0 && b === 3) ||
        (Y === 3 && b === 0) ||
        P5_XING3.some((g) => g.includes(Y) && g.includes(b))));
  if (xing) r.push({ k: "刑", n: Y === b ? "自刑" : "刑太岁", tone: "xiong" });
  if (P5_PAIR(P5_PO, Y, b)) r.push({ k: "破", n: "破太岁", tone: "xiong" });
  if (P5_PAIR(P5_HAI, Y, b)) r.push({ k: "害", n: "害太岁", tone: "xiong" });
  if (P5_PAIR(P5_HE6, Y, b)) r.push({ k: "合", n: "六合太岁", tone: "ji" });
  if (Y !== b && P5_HE3.some((g) => g.includes(Y) && g.includes(b)))
    r.push({ k: "三合", n: "三合太岁", tone: "ji" });
  return r;
}
/* ---------- 八宅命卦(东四/西四) ---------- */
function p5Minggua(birthYear, gender) {
  // gender:'M'|'F',birthYear 以立春为界的“年”
  let s = 0;
  String(birthYear)
    .split("")
    .forEach((d) => {
      s += +d;
    });
  while (s > 9) {
    let t = 0;
    String(s)
      .split("")
      .forEach((d) => {
        t += +d;
      });
    s = t;
  }
  let n = gender === "M" ? 11 - s : s + 4; // 九年一循环:男逐年递减、女逐年递增,对所有年份通用(与“后两位数字和”口径等价)
  while (n > 9) n -= 9;
  while (n <= 0) n += 9;
  if (n === 5) n = gender === "M" ? 2 : 8;
  const G = { 1: "坎", 2: "坤", 3: "震", 4: "巽", 6: "乾", 7: "兑", 8: "艮", 9: "离" };
  return { n, gua: G[n], east: [1, 3, 4, 9].includes(n) };
}
