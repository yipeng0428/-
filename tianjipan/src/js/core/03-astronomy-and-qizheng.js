function tjLifeDaysMeta(R, mode) {
  try {
    const c = R && R.t && R.t.civ;
    if (!c) return "";
    const n = nowBJ();
    const b = Date.UTC(+c.y, (+c.m || 1) - 1, +c.d || 1, +c.h || 0, +c.mi || 0, +c.s || 0);
    const a = Date.UTC(+n.y, (+n.m || 1) - 1, +n.d || 1, +n.h || 0, +n.mi || 0, +n.s || 0);
    const days = Math.floor((a - b) / 864e5);
    if (!Number.isFinite(days) || days < 1 || days > 50000) return "";
    const years = (days / 365.2425).toFixed(1);
    const ds = days.toLocaleString("zh-CN");
    if (mode === "ziwei")
      return `<div class="tj-life-inline" title="按当前北京时间与该命盘出生时刻计算">生命历程 · 已出生 <b>${ds}</b> 天 <span>≈ ${years} 年</span></div>`;
    return `<span class="tj-life-stat" title="按当前北京时间与该命盘出生时刻计算"><small>生命历程</small><b>已出生 ${ds} 天</b><em>≈ ${years} 年</em></span>`;
  } catch (_) {
    return "";
  }
}
