function frame(ts) {
  dial.sweep.setAttribute("transform", `rotate(${((ts / 1000) * 22) % 360})`);
  if (dial.spin.active) {
    const p = Math.min(1, (ts - dial.spin.t0) / dial.spin.dur),
      e = 1 - Math.pow(1 - p, 4);
    dial.rings.forEach((r) =>
      r.g.setAttribute("transform", `rotate(${(r.dir * r.turns * 360 * (1 - e)).toFixed(2)})`),
    );
    /* 首页主动推演转盘也接入同一套机械音效。用实际角速度决定声音密度 / 音量 / 明亮度。 */
    const sr = dial.rings[0],
      a = sr ? sr.dir * sr.turns * 360 * (1 - e) : 0,
      sp = dial.spin;
    if (sp.lastA !== null && sp.lastTs) {
      const dt = Math.max(0.008, (ts - sp.lastTs) / 1000),
        da = a - sp.lastA,
        spd = Math.abs(da) / dt,
        norm = Math.max(0, Math.min(1, spd / 520));
      sp.sAcc += Math.abs(da);
      const gap = 7.2 - 4.8 * norm,
        det = Math.floor(Math.abs(sp.lastA) / 15) !== Math.floor(Math.abs(a) / 15);
      if (det) {
        stuSfxTick(0.32 + 0.58 * norm, true, da < 0 ? -1 : 1, norm);
        sp.sAcc = 0;
      } else if (sp.sAcc >= gap) {
        stuSfxTick(0.18 + 0.62 * norm, false, da < 0 ? -1 : 1, norm);
        sp.sAcc %= gap;
      }
    }
    sp.lastA = a;
    sp.lastTs = ts;
    if (p >= 1) {
      dial.spin.active = false;
      if (!sp.ended) {
        sp.ended = true;
        stuSfxClunk();
      }
    }
  } else {
    const t = { g: dial.tj };
    t.g.setAttribute("transform", `rotate(${((ts / 1000) * 10) % 360})`);
  }
  if (document.hidden) {
    dial._raf = 0;
    return;
  }
  dial._raf = requestAnimationFrame(frame);
}
