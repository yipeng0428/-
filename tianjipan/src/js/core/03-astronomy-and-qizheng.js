function qzCalc(R) {
  const jdUT = R.t.jdUT,
    pl = R.astro && R.astro.planets ? R.astro.planets : asPlanets(jdUT);
  const seven = [
    ["日", pl[0]],
    ["月", pl[1]],
    ["水", pl[2]],
    ["金", pl[3]],
    ["火", pl[4]],
    ["木", pl[5]],
    ["土", pl[6]],
  ];
  const lh = qzNode(jdUT);
  const stars = seven.map((a) => ({ n: a[0], lon: a[1].lon, retro: !!a[1].retro }));
  stars.push(
    { n: "罗睺", lon: lh, retro: false },
    { n: "计都", lon: norm360(lh + 180), retro: false },
    { n: "月孛", lon: qzYuebei(jdUT), retro: false },
    { n: "紫炁", lon: qzZiqi(jdUT), retro: false },
  );
  stars.forEach((s) => {
    s.gong = qzGong(s.lon);
    s.xiu = qzXiu(s.lon);
    s.duzhu = qzDuzhu(s.xiu.name);
    const xl = QZ_XL[s.n];
    s.xl = xl
      ? (s.gong.zhi === xl.m ? "庙" : "") +
          (xl.w.indexOf(s.gong.zhi) >= 0 ? "旺" : "") +
          (s.gong.zhi === xl.x ? "喜" : "") +
          (xl.l.indexOf(s.gong.zhi) >= 0 ? "乐" : "") || "平"
      : "—";
  });
  const sunG = qzGong(pl[0].lon),
    monG = qzGong(pl[1].lon);
  const tZhi = QZ_GZ.indexOf(ZHI[R.bz.pill[3].b]);
  const sIdx = QZ_GZ.indexOf(sunG.zhi),
    mIdx = QZ_GZ.indexOf(monG.zhi);
  const mingIdx = (sIdx + 3 - tZhi + 120) % 12,
    mingZhi = QZ_GZ[mingIdx];
  const palaces = [];
  for (let k = 0; k < 12; k++) {
    const z = QZ_GZ[(mingIdx - k + 24) % 12];
    palaces.push({
      name: QZ_GONG[k],
      zhi: z,
      zhu: QZ_MINGZHU[z],
      qiang: QZ_QIANG.indexOf(QZ_GONG[k]) >= 0,
      stars: [],
    });
  }
  stars.forEach((s) => {
    const p = palaces.find((p) => p.zhi === s.gong.zhi);
    if (p) p.stars.push(s.n);
  });
  const mingDuXiu = qzXiu(QZ_H.indexOf(mingZhi) * 30 + sunG.du);
  const ys = GAN[R.bz.pill[0].s];
  let isDay = null;
  try {
    const o = R.opt || {};
    isDay =
      nwSun(jdUT, Number.isFinite(o.lon) ? o.lon : 120, Number.isFinite(o.lat) ? o.lat : 24.5).alt >
      0;
  } catch (e) {}
  return {
    stars,
    palaces,
    mingZhi,
    mingZhu: QZ_MINGZHU[mingZhi],
    mingDuZhu: qzDuzhu(mingDuXiu.name),
    mingDuXiu,
    shenA: QZ_GZ[(9 + sIdx - tZhi + 120) % 12],
    shenB: QZ_GZ[(9 + mIdx - tZhi + 120) % 12],
    huaYao: QZ_HY[ys],
    yearStem: ys,
    isDay,
    sunLon: pl[0].lon,
  };
}
