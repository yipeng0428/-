function p5Directions(R, Y, gender, birthYear, youNianFn) {
  const dirs = P5_D8.map(([n, gua, deg]) => ({ n, gua, deg, ev: [] }));
  const by = (n) => dirs.find((d) => d.n === n);
  // 奇门(当前排盘时刻)
  if (R && R.qm && R.qm.cells) {
    for (const dn in P5_PAL_OF_DIR) {
      const c = R.qm.cells[P5_PAL_OF_DIR[dn]];
      if (!c) continue;
      const dt = P5_DOOR_TONE[c.door] || "zhong",
        st = P5_STAR_TONE[c.star] || "zhong",
        kong = (c.tags || []).some((t) => t.n === "空亡");
      by(dn).ev.push({
        sys: "奇门",
        tone: dt,
        text: `${c.door}门 · 天${c.star} · ${c.god}${kong ? " · 落空亡" : ""}`,
        sub: st === "ji" ? "星吉" : st === "xiong" ? "星凶" : "星平",
      });
    }
  }
  // 玄空流年飞星 + 气学五黄/暗剑
  const sha = p5YearSha(Y);
  for (const p in sha.fly) {
    if (+p === 5) continue;
    const dn = XK_PAL_DIR[p],
      st = sha.fly[p];
    by(dn).ev.push({
      sys: "玄空流年",
      tone: P5_XKLUCK[st],
      text: `${"一二三四五六七八九"[st - 1]}${["贪狼", "巨门", "禄存", "文曲", "廉贞", "武曲", "破军", "左辅", "右弼"][st - 1]}星`,
    });
  }
  if (sha.wuhuang.dir && sha.wuhuang.dir !== "中")
    by(sha.wuhuang.dir).ev.push({ sys: "气学", tone: "xiong", text: "五黄煞(五黄所在方)" });
  if (sha.anjian.dir)
    by(sha.anjian.dir).ev.push({ sys: "气学", tone: "xiong", text: "暗剑煞(五黄对宫)" });
  // 太岁三煞
  by(sha.taisui.dir[0]).ev.push({
    sys: "太岁三煞",
    tone: "zhong",
    text: `太岁(${sha.taisui.zhi}) · 传统忌动土`,
  });
  by(sha.suipo.dir[0]).ev.push({
    sys: "太岁三煞",
    tone: "xiong",
    text: `岁破(${sha.suipo.zhi}) · 传统忌冲犯`,
  });
  sha.sansha.items.forEach((it) =>
    by(it.dir[0]).ev.push({
      sys: "太岁三煞",
      tone: "xiong",
      text: `${it.n}(${it.zhi}) · 传统忌动土安床`,
    }),
  );
  // 八宅命卦
  if (gender && birthYear && youNianFn) {
    const mg = p5Minggua(birthYear, gender),
      yn = youNianFn(mg.gua);
    if (yn)
      yn.forEach((c) => {
        const tone = ["生气", "延年", "天医", "伏位"].includes(c.name) ? "ji" : "xiong";
        by(c.dir).ev.push({
          sys: "八宅命卦",
          tone,
          text: `${c.name}(${mg.gua}命${mg.east ? "东四" : "西四"})`,
        });
      });
  }
  dirs.forEach((d) => {
    d.ji = d.ev.filter((e) => e.tone === "ji").length;
    d.xiong = d.ev.filter((e) => e.tone === "xiong").length;
  });
  return { dirs, sha };
}

