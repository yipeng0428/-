const SV = "http://www.w3.org/2000/svg";
function E(tag, attrs, parent, text) {
  const e = document.createElementNS(SV, tag);
  for (const k in attrs) e.setAttribute(k, attrs[k]);
  if (text != null) e.textContent = text;
  if (parent) parent.appendChild(e);
  return e;
}
const P = (r, a) => {
  const t = (a * Math.PI) / 180;
  return [r * Math.sin(t), -r * Math.cos(t)];
};
function sector(r1, r2, a1, a2) {
  const [x1, y1] = P(r2, a1),
    [x2, y2] = P(r2, a2),
    [x3, y3] = P(r1, a2),
    [x4, y4] = P(r1, a1);
  const lg = a2 - a1 > 180 ? 1 : 0;
  return `M${x1.toFixed(2)},${y1.toFixed(2)}A${r2},${r2} 0 ${lg} 1 ${x2.toFixed(2)},${y2.toFixed(2)}L${x3.toFixed(2)},${y3.toFixed(2)}A${r1},${r1} 0 ${lg} 0 ${x4.toFixed(2)},${y4.toFixed(2)}Z`;
}
function txt(parent, str, r, a, cls, fs) {
  const [x, y] = P(r, a),
    A = ((a % 360) + 360) % 360,
    rot = A > 90 && A < 270 ? a + 180 : a;
  return E(
    "text",
    {
      transform: `translate(${x.toFixed(2)} ${y.toFixed(2)}) rotate(${rot})`,
      class: cls,
      "text-anchor": "middle",
      "dominant-baseline": "central",
      "font-size": fs,
    },
    parent,
    str,
  );
}
function line(parent, r1, r2, a, cls) {
  const [x1, y1] = P(r1, a),
    [x2, y2] = P(r2, a);
  return E(
    "line",
    { x1: x1.toFixed(2), y1: y1.toFixed(2), x2: x2.toFixed(2), y2: y2.toFixed(2), class: cls },
    parent,
  );
}
function symbol(parent, lines, R, a, w, lh, gap, cls) {
  // 卦画:初爻最靠近圆心
  const g = E("g", { transform: `rotate(${a}) translate(0,${-R})`, class: cls }, parent),
    n = lines.length,
    tot = n * lh + (n - 1) * gap;
  lines.forEach((v, i) => {
    const y = tot / 2 - lh - i * (lh + gap);
    if (v) E("rect", { x: -w / 2, y: y, width: w, height: lh }, g);
    else {
      E("rect", { x: -w / 2, y: y, width: w * 0.42, height: lh }, g);
      E("rect", { x: w / 2 - w * 0.42, y: y, width: w * 0.42, height: lh }, g);
    }
  });
  return g;
}

