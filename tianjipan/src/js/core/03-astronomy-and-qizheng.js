function dayanStalks(rand) {
  const YN = ["初", "二", "三", "四", "五", "上"],
    YN2 = { 6: "老阴 ×", 7: "少阳 ─", 8: "少阴 - -", 9: "老阳 ○" };
  const sums = [],
    logs = [];
  for (let i = 0; i < 6; i++) {
    let n = 49;
    const steps = [n];
    for (let c = 0; c < 3; c++) {
      const left = 1 + Math.floor(rand() * (n - 1)),
        right = n - left - 1; // 分二、挂一
      n = n - 1 - (left % 4 || 4) - (right % 4 || 4); // 揲四、归奇
      steps.push(n);
    }
    const v = n / 4;
    sums.push(v);
    logs.push(`${YN[i]}爻 ${steps.join("→")},得${v}(${YN2[v]})`);
  }
  return { sums, logs };
}

